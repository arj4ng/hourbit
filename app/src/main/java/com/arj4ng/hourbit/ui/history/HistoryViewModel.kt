class HistoryViewModel(
    private val repository: WorkSessionRepository
) : ViewModel() {

    val workSessions: StateFlow<List<WorkSession>> =
        repository.getAllWorkSessions()
            .stateIn(
                scope = viewModelScope,
                started = SharingStarted.WhileSubscribed(5000),
                initialValue = emptyList()
            )

    // delete a saved work session through the repository
    fun deleteWorkSession(workSession: WorkSession) {
        viewModelScope.launch {
            repository.deleteWorkSession(workSession)
        }
    }
}
